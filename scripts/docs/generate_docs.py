# ---------- loading ----------
class Model:
    def __init__(self, src=SRC):
        self.types = []
        for root, _dirs, files in sorted(os.walk(src)):
            for name in sorted(files):
                if name.endswith(".java"):
                    self.types += jp.parse_file(os.path.join(root, name))
        self.by_qualified = {t.qualified: t for t in self.types}
        self.by_package = defaultdict(list)
        for t in self.types:
            self.by_package[short_package(t.package)].append(t)

    def resolve(self, name, context):
        """The type a simple name refers to inside `context` (same package or nested, or an explicit import)."""
        node = context
        while node is not None:                      # nested types of this type or its outers
            for n in node.nested:
                if n.name == name:
                    return n
            node = node.outer
        top = context
        while top.outer is not None:
            top = top.outer
        same = self.by_qualified.get(f"{context.package}.{name}")
        if same is not None:
            return same
        imported = top.imports.get(name)
        return self.by_qualified.get(imported) if imported else None


def short_package(package):
    rest = package[len(BASE):].lstrip(".") if package.startswith(BASE) else package
    return rest or "root"


def type_id(t):
    return re.sub(r"\W", "_", f"{short_package(t.package)}_{t.local_name}")


def label(t):
    return t.local_name


# ---------- relationships ----------
def refs(model, t):
    """-> {target type: set of reasons}: extends / implements / field or component / constructor parameter."""
    out = defaultdict(set)
    for ex in t.extends:
        target = model.resolve(re.sub(r"<.*", "", ex).strip(), t)
        if target is not None:
            out[target].add("extends")
    for im in t.implements:
        target = model.resolve(re.sub(r"<.*", "", im).strip(), t)
        if target is not None:
            out[target].add("implements")
    for inner in t.nested:
        out[inner].add("nested")
    for m in t.members:
        if m.kind in ("field", "component"):
            for n in sorted(jp.referenced_names(m.type)):
                target = model.resolve(n, t)
                if target is not None and target is not t:
                    out[target].add("has")
        elif m.kind == "constructor":
            for p in m.params:
                for n in sorted(jp.referenced_names(p.type)):
                    target = model.resolve(n, t)
                    if target is not None and target is not t:
                        out[target].add("uses")
        elif m.kind == "method" and m.visibility != "private":
            names = set(jp.referenced_names(m.type))
            for p in m.params:
                names |= jp.referenced_names(p.type)
            for n in sorted(names):
                target = model.resolve(n, t)
                if target is not None and target is not t:
                    out[target].add("signature")
    return out


def mermaid_type(text):
    """A Java type for a Mermaid member line: generics use ~, nothing else Mermaid dislikes."""
    text = text.replace("?", "any").replace("&", "and")
    depth, out = 0, []
    for ch in text:
        if ch == "<":
            out.append("~")
            depth += 1
        elif ch == ">":
            out.append("~")
            depth -= 1
        elif ch == ",":
            out.append(", ")
        else:
            out.append(ch)
    return re.sub(r"\s+", " ", "".join(out)).replace("~ ", "~").strip()


def member_line(t, m):
    mark = {"public": "+", "protected": "#", "private": "-", "package": "~"}[m.visibility]
    if m.kind in ("field", "component"):
        return f"{mark}{mermaid_type(m.type)} {m.name}" + ("$" if m.static else "")
    if m.kind == "constant":
        return f"{m.name}"
    params = ", ".join(f"{mermaid_type(p.type)} {p.name}" for p in m.params)
    if m.kind == "constructor":
        return f"{mark}{t.name}({params})"
    return f"{mark}{m.name}({params}) {mermaid_type(m.type)}" + ("$" if m.static else "")


def shown_members(t, with_private_methods=False):
    out = []
    for m in t.members:
        if m.kind == "method" and m.visibility == "private" and not with_private_methods:
            continue
        if m.kind == "constructor" and m.visibility == "private":
            continue
        out.append(m)
    return out


def class_block(t, members=True, limit=40):
    kind_note = {"interface": "<<interface>>", "enum": "<<enumeration>>", "record": "<<record>>"}.get(t.kind)
    if t.kind == "class" and "abstract" in t.modifiers:
        kind_note = "<<abstract>>"
    stereo = None
    if t.annotation("RestController"):
        stereo = "<<controller>>"
    elif t.annotation("Component") or t.annotation("Configuration"):
        stereo = "<<spring>>"
    lines = [f'    class {type_id(t)}["{label(t)}"]']
    inner = []
    if kind_note or stereo:
        inner.append(f"        {kind_note or stereo}")
    if members:
        ms = shown_members(t)
        for m in ms[:limit]:
            inner.append("        " + member_line(t, m))
        if len(ms) > limit:
            inner.append(f"        +{len(ms) - limit} more ...")
    if inner:
        lines[0] += " {"
        lines += inner
        lines.append("    }")
    return lines


LIMIT_NEIGHBOURS = 16
ARROW = {"extends": "<|--", "implements": "<|..", "has": "-->", "uses": "..>", "signature": "..>", "nested": "*--"}


def relation_lines(source, target, reasons):
    """Mermaid lines for one pair; the strongest reason wins so a pair is drawn once."""
    for reason in ("extends", "implements", "nested", "has", "uses", "signature"):
        if reason in reasons:
            if reason in ("extends", "implements"):
                return [f"    {type_id(target)} {ARROW[reason]} {type_id(source)}"]
            return [f"    {type_id(source)} {ARROW[reason]} {type_id(target)}"]
    return []


def overview_diagram(model, types):
    """All types of a package as bare boxes with the relationships among them."""
    lines = ["```mermaid", "classDiagram", "    direction LR"]
    for t in types:
        lines += class_block(t, members=False)
    inside = set(types)
    for t in types:
        for target, reasons in refs(model, t).items():
            if target in inside:
                lines += relation_lines(t, target, reasons)
    lines.append("```")
    return lines


def class_diagram(model, t, incoming):
    """One type with its members, the types it points to and the types that point to it (bare boxes)."""
    lines = ["```mermaid", "classDiagram", "    direction LR"]
    lines += class_block(t, members=True)
    neighbours = []
    out = refs(model, t)
    for target in out:
        if target not in neighbours:
            neighbours.append(target)
    for source in incoming.get(t, {}):
        if source not in neighbours:
            neighbours.append(source)
    rank = {"extends": 0, "implements": 0, "nested": 0, "has": 1, "uses": 2, "signature": 3}

    def strength(n):
        reasons = out.get(n, set()) | incoming.get(t, {}).get(n, set())
        return min(rank[r] for r in reasons)

    neighbours.sort(key=strength)                      # stable: structure first, then the types in signatures
    shown = neighbours[:LIMIT_NEIGHBOURS]
    for n in shown:
        lines += class_block(n, members=False)
    for target, reasons in out.items():
        if target in shown:
            lines += relation_lines(t, target, reasons)
    for source, reasons in incoming.get(t, {}).items():
        if source in shown:
            lines += relation_lines(source, t, reasons)
    if len(neighbours) > LIMIT_NEIGHBOURS:
        lines.append(f"    %% {len(neighbours) - LIMIT_NEIGHBOURS} more neighbours not drawn")
    lines.append("```")
    return lines


# ---------- text helpers ----------
def md_escape(text):
    return text.replace("|", "\\|").replace("\n", " ")


def plain_type(text):
    return re.sub(r"\s+", " ", text).strip()


def signature(t, m):
    params = ", ".join(f"{plain_type(p.type)} {p.name}" for p in m.params)
    if m.kind == "constructor":
        return f"{t.name}({params})"
    return f"{plain_type(m.type)} {m.name}({params})"


def gh_anchor(heading):
    """The id GitHub gives a heading: lower case, punctuation dropped (not - or _), spaces become -."""
    return re.sub(r"\s", "-", re.sub(r"[^a-z0-9 _\-]", "", heading.lower()).strip())


def anchor(t):
    return gh_anchor(t.local_name)


def role_of(t):
    if t.annotation("RestController"):
        return "REST controller"
    if t.annotation("RestControllerAdvice"):
        return "error handler"
    if t.annotation("Configuration"):
        return "configuration"
    if t.annotation("Component"):
        return "Spring component"
    if any(m.kind == "method" and m.name == "main" and m.static for m in t.members):
        return "command-line tool"
    return ""


# ---------- class pages ----------
def incoming_map(model):
    inc = defaultdict(lambda: defaultdict(set))
    for t in model.types:
        for target, reasons in refs(model, t).items():
            inc[target][t] |= reasons
    return inc


def package_page(model, pkg, types, incoming):
    top = [t for t in types if t.outer is None]
    lines = [GENERATED, "", f"# Package `{pkg}`", "", PACKAGE_BLURB.get(pkg, ""), "",
             f"{len(types)} types in {len({t.file for t in types})} source files "
             f"(`src/main/java/de/dahaem/{'' if pkg == 'root' else pkg}`). "
             "Back to the [class index](README.md).", "", "## Overview", ""]
    lines += overview_diagram(model, types)
    lines += ["", "Arrows: `-->` has a field or record component of that type, `..>` takes it in its constructor or "
              "mentions it in a method signature, `<|--` extends, `<|..` implements, `*--` nested type. Only relationships inside this package are drawn here; each class "
              "below also shows its neighbours in other packages.", "", "| Type | Kind | Role | What it is |",
              "|------|------|------|------------|"]
    for t in types:
        lines.append(f"| [`{t.local_name}`](#{anchor(t)}) | {t.kind} | {role_of(t)} | "
                     f"{md_escape(jp.first_sentence(t.doc))} |")
    for t in types:
        lines += ["", f"## {t.local_name}", ""]
        kinds = [t.kind] + ([role_of(t)] if role_of(t) else [])
        if t.extends or t.implements:
            if t.extends:
                kinds.append("extends " + ", ".join(t.extends))
            if t.implements:
                kinds.append("implements " + ", ".join(t.implements))
        lines += ["*" + " · ".join(kinds) + "*", ""]
        if t.doc:
            lines += [t.doc, ""]
        lines += class_diagram(model, t, incoming)
        ms = [m for m in t.members if m.kind == "constant"]
        if ms:
            lines += ["", "**Values:** " + ", ".join(f"`{m.name}`" for m in ms)]
        fields = [m for m in t.members if m.kind in ("field", "component")]
        if fields:
            lines += ["", "| " + ("Component" if t.kind == "record" else "Field") + " | Type |", "|---|---|"]
            for m in fields:
                lines.append(f"| `{m.name}` | `{md_escape(plain_type(m.type))}` |")
        methods = [m for m in t.members if m.kind in ("constructor", "method") and m.visibility != "private"]
        if methods:
            lines += ["", "| Member | Visibility | What it does |", "|---|---|---|"]
            for m in methods:
                what = md_escape(jp.first_sentence(m.doc)) if m.doc else ""
                lines.append(f"| `{md_escape(signature(t, m))}` | {m.visibility}{' static' if m.static else ''} | {what} |")
        used_by = sorted({s.local_name for s in incoming.get(t, {}) if short_package(s.package) != pkg or s.outer is None
                          and s is not t})
        if used_by:
            lines += ["", "**Referenced by:** " + ", ".join(f"`{u}`" for u in used_by[:25])
                      + (" …" if len(used_by) > 25 else "")]
    return "\n".join(lines).rstrip() + "\n"


def package_graph(model):
    deps = defaultdict(Counter)
    for t in model.types:
        if t.outer is not None:
            continue
        src = short_package(t.package)
        for qualified in t.imports.values():
            dst = short_package(qualified.rsplit(".", 1)[0]) if qualified.rsplit(".", 1)[0] != BASE else "root"
            if dst != src and dst in model.by_package:
                deps[src][dst] += 1
    return deps


def classes_index(model, incoming):
    deps = package_graph(model)
    lines = [GENERATED, "", "# Class reference", "",
             "Every class, record, interface and enum of the Java backend, one page per package. Each type has its own "
             "class diagram (members and direct neighbours), its description from the javadoc and a member table. "
             "Everything here is generated from `src/main/java`; the HTTP API is in [API.md](../API.md), the actors "
             "and tools in [USE_CASES.md](../USE_CASES.md), the layering rules in [ARCHITECTURE.md](../ARCHITECTURE.md).",
             "", "## Packages and their imports", "",
             "```mermaid", "flowchart TD"]
    for pkg in sorted(model.by_package):
        lines.append(f'    {pkg}["{pkg} ({len(model.by_package[pkg])})"]')
    shared_users = [p for p in model.by_package if p != "shared" and deps[p].get("shared")]
    for src in sorted(deps):
        for dst, n in sorted(deps[src].items()):
            if dst == "shared":
                continue
            lines.append(f"    {src} -->|{n}| {dst}")
    lines += ["```", "",
              f"Arrows point from the importing package to the imported one; the number is how many import lines. "
              f"`shared` is left out of the drawing: {len(shared_users)} of the other packages import it, and it "
              f"imports none of them. A package that imports nothing else here is a leaf.", "",
              "## Packages", "", "| Package | Types | What it holds |", "|---|---|---|"]
    for pkg in sorted(model.by_package):
        lines.append(f"| [`{pkg}`]({pkg}.md) | {len(model.by_package[pkg])} | {PACKAGE_BLURB.get(pkg, '')} |")
    lines += ["", "## Every type", "", "| Type | Package | Kind | What it is |", "|---|---|---|---|"]
    for t in sorted(model.types, key=lambda x: (x.local_name.lower(), x.package)):
        pkg = short_package(t.package)
        lines.append(f"| [`{t.local_name}`]({pkg}.md#{anchor(t)}) | {pkg} | {t.kind} | "
                     f"{md_escape(jp.first_sentence(t.doc))} |")
    return "\n".join(lines) + "\n"


# ---------- API ----------
HTTP = {"GetMapping": "GET", "PostMapping": "POST", "PutMapping": "PUT", "DeleteMapping": "DELETE",
        "PatchMapping": "PATCH"}






class Endpoint:
    def __init__(self, controller, method, http, path, doc, status):
        self.controller, self.method, self.http, self.path, self.doc, self.status = \
            controller, method, http, path, doc, status
        self.path_params, self.query_params, self.body, self.returns = [], [], None, ""




def read_controllers(model):
    """Endpoint list from the Spring annotations. The parser blanks string literals, so the annotation texts are
    read again from the file."""
    endpoints = []
    for t in model.types:
        if not t.annotation("RestController"):
            continue
        with open(t.file, encoding="utf-8") as f:
            source = f.read()
        base = ""
        m = re.search(r'@RequestMapping\(\s*(?:value\s*=\s*|path\s*=\s*)?"([^"]*)"', source)
        if m:
            base = m.group(1)
        for member in t.members:
            if member.kind != "method":
                continue
            ann = next((a for a in member.annotations if a[0] in HTTP), None)
            if ann is None:
                continue
            decl = re.search(r"((?:@\w+(?:\([^)]*\))?\s*)*)(?:public\s+)?[\w<>\[\], ?]+\s+" + re.escape(member.name)
                             + r"\s*\(", source)
            # the annotations of this method, with their string arguments
            window = source[max(0, decl.start() - 400):decl.end()] if decl else ""
            window = window[window.rfind("*/") + 2:] if "*/" in window else window
            sub = re.search(rf'@{ann[0]}(?:\(\s*(?:value\s*=\s*|path\s*=\s*)?"([^"]*)")?', window)
            path = sub.group(1) if sub and sub.group(1) else ""
            status = "200"
            st = re.search(r"@ResponseStatus\(\s*(?:HttpStatus\.)?(?:value\s*=\s*(?:HttpStatus\.)?)?(\w+)", window)
            if st:
                status = {"CREATED": "201", "NO_CONTENT": "204", "ACCEPTED": "202"}.get(st.group(1), st.group(1))
            ep = Endpoint(t, member, HTTP[ann[0]], base + path, member.doc, status)
            params_src = source[decl.end() - 1:] if decl else ""
            params_src = params_src[1:jp.match_close(params_src, 0, "(", ")")] if params_src.startswith("(") else ""
            for part in jp.split_top(params_src):
                pm = re.search(r"@(RequestParam|PathVariable|RequestBody)(?:\(([^)]*)\))?", part)
                if not pm:
                    continue
                _anns, rest = jp.take_annotations(part)
                rest = " ".join(rest.split())
                tm = re.match(r"(.+?)\s+(\w+)$", rest)
                ptype, pname = (tm.group(1), tm.group(2)) if tm else ("", "")
                argtext = pm.group(2) or ""
                nm = re.search(r'name\s*=\s*"([^"]*)"|value\s*=\s*"([^"]*)"|^\s*"([^"]*)"', argtext)
                name = next((g for g in nm.groups() if g), pname) if nm else pname
                if pm.group(1) == "RequestBody":
                    ep.body = ptype
                elif pm.group(1) == "PathVariable":
                    ep.path_params.append((name, ptype))
                else:
                    default = re.search(r'defaultValue\s*=\s*"([^"]*)"', argtext)
                    required = not re.search(r"required\s*=\s*false", argtext) and not default
                    ep.query_params.append((name, ptype, required, default.group(1) if default else None))
            ep.returns = member.type
            endpoints.append(ep)
    return endpoints


JSON_SAMPLE = {"int": "0", "Integer": "0", "long": "0", "Long": "0", "double": "0.0", "Double": "0.0",
               "float": "0.0", "BigDecimal": "0.00", "boolean": "false", "Boolean": "false", "String": '"…"',
               "LocalDate": '"2026-10-14"', "LocalDateTime": '"2026-10-14T08:00:00"', "Instant": '"2026-10-14T08:00:00Z"'}


def sample(model, context, type_text, depth=0, seen=()):
    type_text = plain_type(type_text)
    m = re.match(r"(List|Set|Collection)<(.+)>$", type_text)
    if m:
        return [sample(model, context, m.group(2), depth + 1, seen)]
    m = re.match(r"Map<(.+?),\s*(.+)>$", type_text)
    if m:
        return {"<key>": sample(model, context, m.group(2), depth + 1, seen)}
    m = re.match(r"Optional<(.+)>$", type_text)
    if m:
        return sample(model, context, m.group(1), depth, seen)
    if type_text.endswith("[]"):
        return [sample(model, context, type_text[:-2], depth + 1, seen)]
    if type_text in JSON_SAMPLE:
        return _Raw(JSON_SAMPLE[type_text])
    target = model.resolve(type_text, context)
    if target is None:
        return _Raw('"…"')
    if target.kind == "enum":
        return _Raw('"' + "|".join(c.name for c in target.members if c.kind == "constant") + '"')
    if target.kind == "record" and depth < 4 and target not in seen:
        return {c.name: sample(model, target, c.type, depth + 1, seen + (target,))
                for c in target.members if c.kind == "component"}
    return _Raw("{ … }")


class _Raw(str):
    pass


def dump_json(value, indent=0):
    pad = "  " * indent
    if isinstance(value, _Raw):
        return str(value)
    if isinstance(value, list):
        if not value:
            return "[]"
        inner = dump_json(value[0], indent + 1)
        return "[\n" + pad + "  " + inner + "\n" + pad + "]" if isinstance(value[0], (dict, list)) else f"[{inner}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        rows = [f'{pad}  "{k}": {dump_json(v, indent + 1)}' for k, v in value.items()]
        return "{\n" + ",\n".join(rows) + "\n" + pad + "}"
    return str(value)


def inner_type(type_text):
    m = re.match(r"(?:List|Set|Collection|Optional)<(.+)>$", plain_type(type_text))
    return m.group(1) if m else plain_type(type_text)


def schema_types(model, endpoint, seen):
    """DTO records an endpoint reads or returns, transitively."""
    queue = [(endpoint.controller, inner_type(endpoint.returns))]
    if endpoint.body:
        queue.append((endpoint.controller, inner_type(endpoint.body)))
    while queue:
        context, name = queue.pop()
        for n in sorted(jp.referenced_names(name)):
            target = model.resolve(n, context)
            if target is None or target in seen or target.kind not in ("record", "enum"):
                continue
            if short_package(target.package) in ("api",) or target.kind == "enum" or True:
                seen[target] = None
                for c in target.members:
                    if c.kind == "component":
                        queue.append((target, c.type))


