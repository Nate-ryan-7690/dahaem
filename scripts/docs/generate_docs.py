def api_page(model):
    endpoints = read_controllers(model)
    by_controller = defaultdict(list)
    for ep in endpoints:
        by_controller[ep.controller].append(ep)
    lines = [GENERATED, "", API_INTRO]
    fixed = [("POST", "/api/auth/login", "Log in (form fields `email`, `password`). 204 on success, 401 on a wrong email or password. Handled by Spring Security, not by a controller."),
             ("POST", "/api/auth/logout", "End the session and delete the `JSESSIONID` cookie. 204.")]
    lines += ["| Method | Path | What it does |", "|---|---|---|"]
    rows = [(ep.http, ep.path, jp.first_sentence(ep.doc), ep) for ep in endpoints]
    for http, path, summary in fixed:
        rows.append((http, path, summary, None))
    for http, path, summary, ep in sorted(rows, key=lambda r: (r[1], r[0])):
        link = f"[`{path}`](#{endpoint_anchor(http, path)})" if ep is not None else f"`{path}`"
        lines.append(f"| {http} | {link} | {md_escape(summary)} |")
    seen = {}
    for controller in sorted(by_controller, key=lambda c: min(e.path for e in by_controller[c])):
        eps = sorted(by_controller[controller], key=lambda e: (e.path, e.http))
        lines += ["", f"### {controller.name}", ""]
        if controller.doc:
            lines += [controller.doc, ""]
        for ep in eps:
            schema_types(model, ep, seen)
            lines += endpoint_section(model, ep)
    lines += ["", "## Schemas", "",
              "The records the endpoints above send or receive. Field names are the JSON property names; `null` is "
              "possible for boxed types (`Integer`, `Double` ...) and for objects that are optional."]
    for target in sorted(seen, key=lambda x: x.local_name.lower()):
        lines += ["", f"### {target.local_name}", ""]
        if target.doc:
            lines += [target.doc, ""]
        if target.kind == "enum":
            lines.append("One of: " + ", ".join(f"`{c.name}`" for c in target.members if c.kind == "constant"))
            continue
        lines += ["| Property | Type |", "|---|---|"]
        for c in target.members:
            if c.kind == "component":
                lines.append(f"| `{c.name}` | `{md_escape(plain_type(c.type))}` |")
        lines += ["", "```json", dump_json(sample(model, target, target.name, 0, (target,))), "```"]
    return "\n".join(lines).rstrip() + "\n"


def endpoint_anchor(http, path):
    return gh_anchor(f"{http} {path}")


def endpoint_section(model, ep):
    lines = ["", f"#### {ep.http} {ep.path}", ""]
    if ep.doc:
        lines += [ep.doc, ""]
    if ep.path_params:
        lines += ["**Path parameters**", "", "| Name | Type |", "|---|---|"]
        lines += [f"| `{n}` | `{plain_type(t)}` |" for n, t in ep.path_params]
        lines.append("")
    if ep.query_params:
        lines += ["**Query parameters**", "", "| Name | Type | Required | Default |", "|---|---|---|---|"]
        for n, t, required, default in ep.query_params:
            lines.append(f"| `{n}` | `{md_escape(plain_type(t))}` | {'yes' if required else 'no'} | "
                         f"{'`' + default + '`' if default is not None else ''} |")
        lines += ["", "A list parameter is repeated (`?diet=halal&diet=vegan`) or comma separated (`excludeTags=a,b`)."
                  if any(plain_type(t).startswith("List") for _n, t, _r, _d in ep.query_params) else "", ""]
    if ep.body:
        lines += [f"**Request body** `{plain_type(ep.body)}`", "", "```json",
                  dump_json(sample(model, ep.controller, ep.body)), "```", ""]
    ret = plain_type(ep.returns)
    lines += [f"**Answer** {ep.status} `{ret}`", ""]
    if ret != "void":
        lines += ["```json", dump_json(sample(model, ep.controller, ret)), "```"]
    return lines


