def build(model):
    incoming = incoming_map(model)
    files = {"docs/classes/README.md": classes_index(model, incoming),
             "docs/API.md": api_page(model),
             "docs/USE_CASES.md": use_cases_page(model)}
    for pkg, types in sorted(model.by_package.items()):
        files[f"docs/classes/{pkg}.md"] = package_page(model, pkg, types, incoming)
    return files


def _read(path):
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return f.read()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed files differ from the generated ones")
    ap.add_argument("--root", default=ROOT, help="repository root (default: this checkout)")
    args = ap.parse_args(argv)
    model = Model(os.path.join(args.root, "src", "main", "java"))
    files = build(model)
    stale = []
    for rel, text in files.items():
        path = os.path.join(args.root, rel)
        if args.check:
            current = _read(path)
            if current != text:
                stale.append(rel)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    # a package that no longer exists must not leave its page behind
    classes_dir = os.path.join(args.root, "docs", "classes")
    extra = sorted(f for f in (os.listdir(classes_dir) if os.path.isdir(classes_dir) else [])
                   if f.endswith(".md") and f"docs/classes/{f}" not in files)
    for name in extra:
        if args.check:
            stale.append(f"docs/classes/{name} (no longer generated)")
        else:
            os.remove(os.path.join(classes_dir, name))
    if args.check:
        if stale:
            print("out of date (run python3 scripts/docs/generate_docs.py):", *stale, sep="\n  ")
            return 1
        print("documentation is up to date")
        return 0
    print(f"wrote {len(files)} files: {len(model.types)} types in {len(model.by_package)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
